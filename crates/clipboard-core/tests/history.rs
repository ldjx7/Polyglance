#[test]
fn failed_duplicate_growth_preserves_existing_payload_and_pin() {
    let limits = Limits {
        maximum_bytes: 40,
        maximum_item_bytes: 40,
        ..Limits::default()
    };
    let mut history = History::open(":memory:", limits, 100).unwrap();
    let id = history.record(text("a", 1), &policy()).unwrap().unwrap();
    history.set_pinned(id, true, 100).unwrap();
    let other = history.record(text("b", 2), &policy()).unwrap().unwrap();
    history.set_pinned(other, true, 100).unwrap();
    let before = history.payload(id).unwrap();
    let mut input = text("a", 3);
    input.representations.push(Representation {
        format: "text/html".into(),
        bytes: vec![b'x'; 30],
    });
    assert!(matches!(
        history.record(input, &policy()),
        Err(Error::Capacity) | Err(Error::TooLarge)
    ));
    assert_eq!(history.payload(id).unwrap(), before);
    assert_eq!(list(&mut history)[0].copied_at_ms, 2);
}
